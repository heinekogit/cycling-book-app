export type SavedRoute = {
  elevationProfile?: unknown
  id: string
  name: string
  createdAt: string
  isPublic: boolean
  routeType: string | null
  sourceRunId: string | null
  origin: string | null
  distanceMeters: number
  geojson: unknown
  polyline: string | null
  description: string | null
  elevationGainMeters: number | null
  elevationLossMeters: number | null
  elevationMinMeters: number | null
  elevationMaxMeters: number | null
}

export type RouteCoordinate = { latitude: number; longitude: number }

export function isAutoGeneratedRunRoute(route: Pick<SavedRouteRow, 'origin' | 'route_type' | 'source_run_id'>) {
  return route.origin === 'from_log' && route.route_type === 'from_run' && route.source_run_id == null
}

export function routeTypeKey(route: Pick<SavedRoute, 'origin' | 'routeType' | 'sourceRunId'>) {
  if (route.origin === 'drawn' || route.routeType === 'planned') return 'drawn'
  if (route.routeType === 'from_run' && route.origin === 'manual') return 'drawn'
  if (route.routeType === 'from_run' || route.sourceRunId) return 'fromRun'
  if (route.routeType === 'manual') return 'drawn'
  return 'other'
}

export function normalizeSavedRoute(row: SavedRouteRow, defaultName = 'Untitled route'): SavedRoute {
  const route = {
    elevationProfile: row.elevation_profile,
    id: String(row.id), name: row.name || defaultName, createdAt: row.created_at,
    isPublic: row.is_public === true, routeType: row.route_type,
    sourceRunId: row.source_run_id == null ? null : String(row.source_run_id), origin: row.origin,
    distanceMeters: Number(row.distance_m) || 0, geojson: row.geojson, polyline: row.polyline,
    description: row.description?.trim() || null,
    elevationGainMeters: finiteNumber(row.elevation_gain_m), elevationLossMeters: finiteNumber(row.elevation_loss_m),
    elevationMinMeters: finiteNumber(row.elevation_min_m), elevationMaxMeters: finiteNumber(row.elevation_max_m),
  }
  if (route.distanceMeters <= 0) route.distanceMeters = routeDistanceMeters(routeCoordinates(route))
  return route
}

function finiteNumber(value: number | null | undefined) {
  const numeric = Number(value)
  return value == null || !Number.isFinite(numeric) ? null : numeric
}

function validCoordinate(value: unknown): RouteCoordinate | null {
  if (!Array.isArray(value) || value.length < 2) return null
  const longitude = Number(value[0]); const latitude = Number(value[1])
  if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) return null
  if (latitude < -90 || latitude > 90 || longitude < -180 || longitude > 180) return null
  return { latitude, longitude }
}

function parseGeoJson(value: unknown): unknown {
  if (typeof value !== 'string') return value
  try {
    const parsed = JSON.parse(value) as unknown
    return typeof parsed === 'string' ? JSON.parse(parsed) as unknown : parsed
  } catch { return null }
}

export function coordinatesFromRouteGeoJson(value: unknown): RouteCoordinate[] {
  const root = parseGeoJson(value)
  if (!root || typeof root !== 'object') return []
  const output: RouteCoordinate[] = []
  const walk = (geometry: unknown) => {
    if (!geometry || typeof geometry !== 'object') return
    const item = geometry as { type?: string; coordinates?: unknown; geometries?: unknown[]; geometry?: unknown; features?: unknown[] }
    if (item.type === 'Feature') return walk(item.geometry)
    if (item.type === 'FeatureCollection') return item.features?.forEach(walk)
    if (item.type === 'GeometryCollection') return item.geometries?.forEach(walk)
    if (item.type === 'LineString' && Array.isArray(item.coordinates)) {
      item.coordinates.forEach((coordinate) => { const point = validCoordinate(coordinate); if (point) output.push(point) })
    }
    if (item.type === 'MultiLineString' && Array.isArray(item.coordinates)) {
      item.coordinates.forEach((line) => { if (Array.isArray(line)) line.forEach((coordinate) => { const point = validCoordinate(coordinate); if (point) output.push(point) }) })
    }
  }
  walk(root)
  return output
}

export function decodePolyline(encoded: string): RouteCoordinate[] {
  try {
    const points: RouteCoordinate[] = []
    let index = 0; let latitude = 0; let longitude = 0
    const read = () => {
      let shift = 0; let result = 0; let byte = 0
      do { byte = encoded.charCodeAt(index++) - 63; result |= (byte & 0x1f) << shift; shift += 5 } while (byte >= 0x20 && index <= encoded.length)
      return result & 1 ? ~(result >> 1) : result >> 1
    }
    while (index < encoded.length) {
      latitude += read(); longitude += read()
      points.push({ latitude: latitude / 1e5, longitude: longitude / 1e5 })
    }
    return points
  } catch { return [] }
}

export function routeCoordinates(route: Pick<SavedRoute, 'geojson' | 'polyline'>) {
  const geoJsonPoints = coordinatesFromRouteGeoJson(route.geojson)
  return geoJsonPoints.length ? geoJsonPoints : route.polyline ? decodePolyline(route.polyline) : []
}

export function routeDistanceMeters(points: RouteCoordinate[]) {
  const radians = (degrees: number) => degrees * Math.PI / 180
  return points.slice(1).reduce((total, point, index) => {
    const previous = points[index]
    const latitudeDelta = radians(point.latitude - previous.latitude)
    const longitudeDelta = radians(point.longitude - previous.longitude)
    const value = Math.sin(latitudeDelta / 2) ** 2 + Math.cos(radians(previous.latitude)) * Math.cos(radians(point.latitude)) * Math.sin(longitudeDelta / 2) ** 2
    return total + 2 * 6_371_000 * Math.asin(Math.sqrt(value))
  }, 0)
}
