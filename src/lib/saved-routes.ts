import type { TFunction } from '@/i18n'
import { isAutoGeneratedRunRoute, normalizeSavedRoute, type SavedRouteRow } from '@/lib/saved-route-model'
import { supabase } from '@/lib/supabase'

const ROUTE_COLUMNS = 'id,name,created_at,is_public,route_type,source_run_id,origin,account_id,distance_m,geojson,polyline,description,elevation_gain_m,elevation_loss_m,elevation_min_m,elevation_max_m'

async function accountIdForUser(userId: string, t: TFunction) {
  const { data, error } = await supabase.from('users').select('account_id').eq('id', userId).maybeSingle()
  if (error) throw error
  if (!data?.account_id) throw new Error(t('accountUnavailable'))
  return data.account_id
}

export async function fetchSavedRoutes(userId: string, t: TFunction) {
  const accountId = await accountIdForUser(userId, t)
  const { data, error } = await supabase.from('routes').select(ROUTE_COLUMNS).eq('account_id', accountId).order('created_at', { ascending: false })
  if (error) throw error
  return ((data ?? []) as SavedRouteRow[]).filter((route) => !isAutoGeneratedRunRoute(route)).map((route) => normalizeSavedRoute(route, t('untitledRoute')))
}

export async function fetchSavedRoute(userId: string, routeId: string, t: TFunction) {
  const accountId = await accountIdForUser(userId, t)
  const { data, error } = await supabase.from('routes').select(`${ROUTE_COLUMNS},elevation_profile`).eq('account_id', accountId).eq('id', routeId).maybeSingle()
  if (error) throw error
  if (!data || isAutoGeneratedRunRoute(data as SavedRouteRow)) return null
  const { data: original, error: originalError } = await supabase.from('route_private_geometries').select('geojson,polyline,distance_m').eq('route_id', routeId).maybeSingle()
  if (originalError) throw originalError
  return normalizeSavedRoute({ ...data, ...(original ?? {}) } as SavedRouteRow, t('untitledRoute'))
}
