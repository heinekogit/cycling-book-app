import assert from 'node:assert/strict'
import test from 'node:test'

import { coordinatesFromRouteGeoJson, decodePolyline, isAutoGeneratedRunRoute, normalizeSavedRoute, routeTypeKey } from '../src/lib/saved-route-model.ts'

test('mypageと同じ条件で実走自動生成ルートを除外する', () => {
  assert.equal(isAutoGeneratedRunRoute({ origin: 'from_log', route_type: 'from_run', source_run_id: null }), true)
  assert.equal(isAutoGeneratedRunRoute({ origin: 'from_log', route_type: 'from_run', source_run_id: 42 }), false)
  assert.equal(isAutoGeneratedRunRoute({ origin: 'drawn', route_type: 'planned', source_run_id: null }), false)
})

test('FeatureとMultiLineStringのGeoJSONから地図座標を取り出す', () => {
  const geojson = { type: 'Feature', geometry: { type: 'MultiLineString', coordinates: [[[139, 35], [139.1, 35.1]], [[139.2, 35.2]]] } }
  assert.deepEqual(coordinatesFromRouteGeoJson(JSON.stringify(geojson)), [
    { latitude: 35, longitude: 139 }, { latitude: 35.1, longitude: 139.1 }, { latitude: 35.2, longitude: 139.2 },
  ])
})

test('古いPolyline形式を地図座標へ変換する', () => {
  assert.deepEqual(decodePolyline('_p~iF~ps|U_ulLnnqC_mqNvxq`@'), [
    { latitude: 38.5, longitude: -120.2 }, { latitude: 40.7, longitude: -120.95 }, { latitude: 43.252, longitude: -126.453 },
  ])
})

test('距離がないルートは軌跡から計算し、種類を判定する', () => {
  const route = normalizeSavedRoute({ id: 4, name: null, created_at: '2026-01-01T00:00:00Z', is_public: false, route_type: 'planned', source_run_id: null, origin: 'drawn', account_id: 1, distance_m: null, geojson: { type: 'LineString', coordinates: [[139, 35], [139, 35.001]] }, polyline: null }, '無題')
  assert.equal(route.name, '無題')
  assert.ok(route.distanceMeters > 100)
  assert.equal(routeTypeKey(route), 'drawn')
})
